use gpui::{actions, App, KeyBinding};

actions!(
    gitter,
    [
        Quit,
        OpenRepository,
        CloneRepository,
        InitRepository,
        NewTab,
        CloseTab,
        NextTab,
        PrevTab,
        OpenSettings,
        ToggleTheme,
        Refresh,
        Fetch,
        Pull,
        Push,
        NewBranch,
        MergeBranch,
        RebaseBranch,
        StashChanges,
        PopStash,
        QuickActions,
        ShowWorkingCopy,
        ShowHistory,
        ShowStashes,
        ShowReflog,
        FocusSearch,
        Cancel,
        Commit,
        SelectPrev,
        SelectNext,
        SelectFirst,
        SelectLast,
        ToggleStage,
        StageAll,
        UnstageAll,
        DiscardSelected,
        OpenTerminal,
        RevealInFiles,
        Confirm,
        Undo,
    ]
);

pub fn bind_keys(cx: &mut App) {
    cx.bind_keys([
        KeyBinding::new("secondary-q", Quit, None),
        KeyBinding::new("secondary-o", OpenRepository, None),
        KeyBinding::new("secondary-shift-o", CloneRepository, None),
        KeyBinding::new("secondary-t", NewTab, None),
        KeyBinding::new("secondary-w", CloseTab, None),
        KeyBinding::new("ctrl-tab", NextTab, None),
        KeyBinding::new("ctrl-shift-tab", PrevTab, None),
        KeyBinding::new("secondary-,", OpenSettings, None),
        KeyBinding::new("secondary-r", Refresh, Some("RepoView")),
        KeyBinding::new("f5", Refresh, Some("RepoView")),
        KeyBinding::new("secondary-shift-f", Fetch, Some("RepoView")),
        KeyBinding::new("secondary-shift-l", Pull, Some("RepoView")),
        KeyBinding::new("secondary-shift-p", Push, Some("RepoView")),
        KeyBinding::new("secondary-b", NewBranch, Some("RepoView")),
        KeyBinding::new("secondary-shift-m", MergeBranch, Some("RepoView")),
        KeyBinding::new("secondary-shift-s", StashChanges, Some("RepoView")),
        KeyBinding::new("secondary-k", QuickActions, Some("RepoView")),
        KeyBinding::new("secondary-shift-a", QuickActions, Some("RepoView")),
        KeyBinding::new("secondary-1", ShowWorkingCopy, Some("RepoView")),
        KeyBinding::new("secondary-2", ShowHistory, Some("RepoView")),
        KeyBinding::new("secondary-3", ShowStashes, Some("RepoView")),
        KeyBinding::new("secondary-4", ShowReflog, Some("RepoView")),
        KeyBinding::new("secondary-f", FocusSearch, Some("RepoView")),
        KeyBinding::new("secondary-enter", Commit, Some("RepoView")),
        KeyBinding::new("secondary-shift-t", OpenTerminal, Some("RepoView")),
        KeyBinding::new("secondary-z", Undo, Some("RepoView")),
        KeyBinding::new("escape", Cancel, None),
        KeyBinding::new("up", SelectPrev, Some("List")),
        KeyBinding::new("down", SelectNext, Some("List")),
        KeyBinding::new("home", SelectFirst, Some("List")),
        KeyBinding::new("end", SelectLast, Some("List")),
        KeyBinding::new("space", ToggleStage, Some("FileList")),
        KeyBinding::new("enter", ToggleStage, Some("FileList")),
        KeyBinding::new("delete", DiscardSelected, Some("FileList")),
        KeyBinding::new("enter", Confirm, Some("Modal")),
    ]);
}
